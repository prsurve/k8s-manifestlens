// Embeds rules/*.yaml in src/rules/bundled.ts so the core needs no file access at runtime.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const files = readdirSync(new URL('rules/', root))
  .filter((f) => f.endsWith('.yaml'))
  .sort();

const entries = files.map(
  (f) =>
    `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(new URL(`rules/${f}`, root), 'utf8'))},`,
);
const out = `// Generated by scripts/bundle-rules.mjs from rules/*.yaml. Do not edit.
export const bundledRuleSources: Record<string, string> = {
${entries.join('\n')}
};
`;
const target = fileURLToPath(new URL('src/rules/bundled.ts', root));
writeFileSync(target, out);
console.log(`Bundled ${files.length} rule files into src/rules/bundled.ts`);
